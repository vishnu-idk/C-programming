//to display length and breadth of a rectangle in floating point datatype
#include <stdio.h>
void main()
{
    float a,b;
    printf("write the length of a rectangle");
    scanf("%f",&a);
    printf("write the breadth of the rectangle");
    scanf("%f",&b);
    
    printf("the length of the rectangle is %f\nthe breadth of the rectangle is %f",a,b);
}
